// ======================================================
// NOMES DAS CATEGORIAS
// ======================================================

const categoryName = {
  roupas: 'Roupas',
  sneakers: 'Sneakers',
  acessorios: 'Acessórios'
};


// ======================================================
// ELEMENTOS
// ======================================================

const cards = document.querySelector('#cards');
const search = document.querySelector('#search');
const filters = [...document.querySelectorAll('.filter')];
const empty = document.querySelector('#empty');

let active = 'all';


// ======================================================
// RENDER DOS CARDS
// ======================================================

function render() {

  const q = search
    ? search.value.trim().toLowerCase()
    : '';

  const items = catalog.filter(item => {

    const categoriaCorreta =
      active === 'all' ||
      item.cat === active;

    const buscaCorreta =
      item.name
        .toLowerCase()
        .includes(q);

    return categoriaCorreta && buscaCorreta;

  });


  cards.innerHTML = items.map(item => {

    const number =
      String(catalog.indexOf(item) + 1)
        .padStart(2, '0');

    return `
      <article class="card" data-tilt>

        <div class="card-media">

          <img
            src="${categoryImage}"
            alt="${item.name}"
            loading="lazy"
            draggable="false"
            referrerpolicy="no-referrer"
          />

          <span class="card-no">
            ${number}
          </span>

          <span class="card-badge">
            ${categoryName[item.cat]}
          </span>

        </div>

        <div class="card-body">

          <h3 class="card-title">
            ${item.name}
          </h3>

          <div class="card-meta">

            <span>
              ${item.extra || 'Catálogo externo'}
            </span>

            <span>
              ↗
            </span>

          </div>

          <a
            class="card-link"
            href="${item.url}"
            target="_blank"
            rel="noopener noreferrer"
          >

            <span>
              Abrir catálogo
            </span>

            <span>
              ↗
            </span>

          </a>

        </div>

      </article>
    `;

  }).join('');


  if (empty) {
    empty.hidden = items.length > 0;
  }

  attachTilt();

}


// ======================================================
// FILTROS
// ======================================================

filters.forEach(btn => {

  btn.addEventListener('click', () => {

    filters.forEach(filter => {
      filter.classList.remove('active');
    });

    btn.classList.add('active');

    active =
      btn.dataset.filter || 'all';

    render();

  });

});


// ======================================================
// BUSCA
// ======================================================

if (search) {

  search.addEventListener(
    'input',
    render
  );

}


// ======================================================
// EFEITO 3D
// ======================================================

function attachTilt() {

  const tiltCards =
    document.querySelectorAll('[data-tilt]');


  tiltCards.forEach(card => {

    card.addEventListener(
      'mousemove',
      handleTilt
    );

    card.addEventListener(
      'mouseleave',
      resetTilt
    );

  });

}


function handleTilt(e) {

  const card =
    e.currentTarget;

  const rect =
    card.getBoundingClientRect();


  const x =
    (e.clientX - rect.left) /
    rect.width -
    0.5;


  const y =
    (e.clientY - rect.top) /
    rect.height -
    0.5;


  const rotateX =
    -y * 7;


  const rotateY =
    x * 9;


  card.style.transform = `
    perspective(850px)
    rotateX(${rotateX}deg)
    rotateY(${rotateY}deg)
    translateY(-5px)
    scale(1.01)
  `;

}


function resetTilt(e) {

  const card =
    e.currentTarget;


  card.style.transform = `
    perspective(850px)
    rotateX(0deg)
    rotateY(0deg)
    translateY(0px)
    scale(1)
  `;

}


// ======================================================
// INICIALIZA
// ======================================================

render();