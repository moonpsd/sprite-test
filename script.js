function attachTilt() {

  const tiltCards =
    document.querySelectorAll('[data-tilt]');


  tiltCards.forEach(card => {

    card.addEventListener(
      'mousemove',
      handleTilt
    );

    card.addEventListener(
      'mouseleave',
      resetTilt
    );

  });

}


function handleTilt(e) {

  const card =
    e.currentTarget;

  const rect =
    card.getBoundingClientRect();


  const x =
    (e.clientX - rect.left) /
    rect.width -
    0.5;


  const y =
    (e.clientY - rect.top) /
    rect.height -
    0.5;


  const rotateX =
    -y * 7;


  const rotateY =
    x * 9;


  card.style.transform = `
    perspective(850px)
    rotateX(${rotateX}deg)
    rotateY(${rotateY}deg)
    translateY(-5px)
    scale(1.01)
  `;

}


function resetTilt(e) {

  const card =
    e.currentTarget;


  card.style.transform = `
    perspective(850px)
    rotateX(0deg)
    rotateY(0deg)
    translateY(0px)
    scale(1)
  `;

}


