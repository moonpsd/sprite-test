// ======================================================
// EFEITO 3D — CARDS SELECIONADOS
// ======================================================

function attachSpecialTilt() {

  const specialCards =
    document.querySelectorAll(
      '[data-special-tilt]'
    );


  specialCards.forEach(card => {

    card.addEventListener(
      'mousemove',
      event => {

        const rect =
          card.getBoundingClientRect();


        const x =
          (
            event.clientX -
            rect.left
          ) /
          rect.width -
          0.5;


        const y =
          (
            event.clientY -
            rect.top
          ) /
          rect.height -
          0.5;


        const rotateX =
          -y * 6;


        const rotateY =
          x * 8;


        card.style.transform = `
          perspective(900px)
          rotateX(${rotateX}deg)
          rotateY(${rotateY}deg)
          translateY(-6px)
          scale(1.015)
        `;

      }
    );


    card.addEventListener(
      'mouseleave',
      () => {

        card.style.transform = `
          perspective(900px)
          rotateX(0deg)
          rotateY(0deg)
          translateY(0)
          scale(1)
        `;

      }
    );

  });

}


