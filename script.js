function formatBRL(value) {

  return value.toLocaleString(
    'pt-BR',
    {
      style: 'currency',
      currency: 'BRL'
    }
  );

}


// ======================================================
// PEGA VALOR DOS INPUTS
// ======================================================

function getValue(input) {

  const value =
    parseFloat(input.value);

  return Number.isFinite(value)
    ? value
    : 0;

}


// ======================================================
// CALCULA
// ======================================================

function calculateImport() {

  const product =
    getValue(productValue);

  const chinaFreight =
    getValue(chinaShipping);

  const chinaTaxes =
    getValue(chinaTax);

  const optionalExtras =
    getValue(extras);

  const internationalFreight =
    getValue(internationalShipping);

  const percentage =
    getValue(taxPercentage);


  // ------------------------------
  // ETAPA 01
  // ------------------------------

  const chinaSubtotal =
    product +
    chinaFreight +
    chinaTaxes +
    optionalExtras;


  // ------------------------------
  // BASE DOS IMPOSTOS
  // ------------------------------

  let taxableValue =
    chinaSubtotal;


  if (taxShipping.checked) {

    taxableValue +=
      internationalFreight;

  }


  // ------------------------------
  // IMPOSTOS
  // ------------------------------

  const estimatedTax =
    taxableValue *
    (percentage / 100);


  // ------------------------------
  // TOTAL FINAL
  // ------------------------------

  const finalValue =
    chinaSubtotal +
    internationalFreight +
    estimatedTax;


  // ------------------------------
  // MOSTRA NA TELA
  // ------------------------------

  chinaTotal.textContent =
    formatBRL(chinaSubtotal);


  shippingTotal.textContent =
    formatBRL(internationalFreight);


  taxBase.textContent =
    formatBRL(taxableValue);


  taxTotal.textContent =
    formatBRL(estimatedTax);


  grandTotal.textContent =
    formatBRL(finalValue);

}


